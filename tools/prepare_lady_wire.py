#!/usr/bin/env python3
"""Export Lady's grapple hook and five-bone cable (em034 PAC 26/30).

FUN_0049e7e0 pairs the hook with texture set 19 and the cable with set 29.
Keep the original skin weights: FUN_0049f020 places the cable's five bones
between Kalina Ann's second bone and the travelling hook. Generated data is
local-only and must not be committed.
"""
import argparse
from pathlib import Path

from dmc3_image import AfsArchive, Iso9660
from prepare_skinned_model import (array_lines, build_mesh, c_float,
                                   decode_textures, indexed_texture, pac_list,
                                   parse_skeleton)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("iso", type=Path)
    ap.add_argument("--output", type=Path, required=True)
    args = ap.parse_args()
    with Iso9660(args.iso) as iso:
        e = AfsArchive(iso, "GDATA.AFS").entries[138]
        pack = pac_list(iso.read_file("GDATA.AFS", e["offset"], e["size"]))
    lines = ["/* Generated by prepare_lady_wire.py; owner's disc data. */", "#pragma once",
             "typedef struct { float u,v; unsigned int color; float x,y,z; } LadyWireVertex;",
             "typedef struct { LadyWireVertex v; unsigned char bones[3],weights[3]; } LadyWireSkin;",
             "typedef struct { const LadyWireSkin *skin; int count,width,height; const unsigned char *pixels;"
             " const unsigned int *palette; } LadyWireBatch;",
             "typedef struct { const LadyWireBatch *batches; int count; const float (*rest)[3]; } LadyWireModel;"]
    table = []
    for name, model, texture in (("hook", 26, 19), ("cable", 30, 29)):
        sk = parse_skeleton(pack[model])
        mesh = build_mesh(pack[model], sk["count"])
        textures = decode_textures(pack[texture])
        prefix = "lady_wire_" + name
        lines += [f"static const float {prefix}_rest[][3] = {{",
                  array_lines(sk["world"], lambda p: "{" + ",".join(map(c_float, p)) + "}"), "};"]
        rows = []
        for j, obj in enumerate(mesh["objects"]):
            tex = textures[obj["texture"]]
            pixels, palette = indexed_texture(tex)
            p = f"{prefix}_{j}"
            verts = []
            for i in mesh["indices"][obj["index_start"]:obj["index_start"] + obj["index_count"]]:
                u, v = mesh["uvs"][i]
                x, y, z = mesh["positions"][i]
                # Original normal-based grey, matching the other rigid props.
                shade = int(150 + 105 * max(0.0, mesh["normals"][i][1]))
                color = 0xff000000 | shade << 16 | shade << 8 | shade
                verts.append("{{%s,%s,0x%08xu,%s,%s,%s},{%s},{%s}}" % (
                    c_float(u), c_float(v), color, c_float(x), c_float(y), c_float(z),
                    ",".join(map(str, mesh["bones"][i])), ",".join(map(str, mesh["weights"][i]))))
            lines += [f"static const LadyWireSkin {p}_skin[] = {{", array_lines(verts, str, 1), "};",
                      f"static const unsigned char {p}_pixels[] __attribute__((aligned(16))) = {{",
                      array_lines(pixels, str, 32), "};",
                      f"static const unsigned int {p}_palette[256] __attribute__((aligned(16))) = {{",
                      array_lines(palette, lambda c: f"0x{c:08x}u", 8), "};"]
            rows.append(f"{{{p}_skin,{len(verts)},{tex['width']},{tex['height']},{p}_pixels,{p}_palette}}")
        lines.append(f"static const LadyWireBatch {prefix}_batches[] = {{" + ",".join(rows) + "};")
        table.append(f"{{{prefix}_batches,{len(rows)},{prefix}_rest}}")
        print(name, len(mesh["indices"]) // 3, "triangles", sk["count"], "bones")
    lines.append("static const LadyWireModel lady_wire_models[] = {" + ",".join(table) + "};")
    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / "lady_wire_runtime.h").write_text("\n".join(lines) + "\n", encoding="ascii")


if __name__ == "__main__":
    main()
