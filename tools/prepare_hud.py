#!/usr/bin/env python3
"""Export the game's cockpit (HUD) from id100.pac -> hud_runtime.h.

id100.pac (GDATA slot 1495) is a PAC of texture sets, each followed by the MODs
that use it. The MODs are flat meshes laid out in screen units: origin at the
screen centre, Y up, about +-320 x +-224. Each is flattened to one triangle list.
"""
import argparse
import struct
from pathlib import Path

from dmc3_image import AfsArchive, Iso9660
from mod_ps2 import parse_mod
from mod_skeleton import parse_skeleton, parse_skin, strip_faces
from tim2 import decode_picture

SLOT = 1495
# What each chunk is, from rendering them all; rank and icons are in weapon / rank order.
CHUNKS = {
    1: "ORBS", 4: "BAR_FRAME", 6: "GEMS", 8: "RETICLE",
    10: "RANK_D", 11: "RANK_C", 12: "RANK_B", 13: "RANK_A", 14: "RANK_S", 15: "RANK_SS", 16: "RANK_SSS",
    19: "STYLE_GOLD", 21: "STYLE_RED", 23: "STYLE_BLUE", 25: "STYLE_GREEN", 27: "STYLE_PURPLE", 29: "STYLE_ORANGE",
    31: "GUN_EBONY_IVORY", 33: "GUN_SHOTGUN", 35: "GUN_ARTEMIS", 37: "GUN_SPIRAL", 39: "GUN_KALINA",
    43: "MELEE_REBELLION", 45: "MELEE_CERBERUS", 47: "MELEE_AGNI", 49: "MELEE_NEVAN", 51: "MELEE_BEOWULF",
}


def split_pac(data):
    count = struct.unpack_from("<I", data, 4)[0]
    offsets = struct.unpack_from(f"<{count}I", data, 8)
    present = sorted(o for o in offsets if o)
    return {i: data[o:min([p for p in present if p > o] + [len(data)])] for i, o in enumerate(offsets) if o}


def first_texture(data):
    count = struct.unpack_from("<I", data, 0)[0]
    image = data[0x800:0x800 + struct.unpack_from(f"<{count}I", data, 4)[0] * 0x800]
    _, rgba, picture = decode_picture(image, 0x80 if image[5] == 1 else 0x10)
    return picture["width"], picture["height"], bytes(rgba)


def triangles(mod):
    skeleton = parse_skeleton(mod)
    objects, _ = parse_mod(mod, split_submeshes=True)
    verts = []
    for obj in objects:
        try:
            _, _, adc = parse_skin(mod, obj["bone_offset"], obj["weight_offset"], obj["vertex_count"], skeleton["count"])
            faces = strip_faces(adc)
        except ValueError:      # some UI meshes have no skin weights
            faces = obj["faces"]
        start = len(verts)
        for face in faces:
            for v in face:
                verts.append((obj["uvs"][v][0], obj["uvs"][v][1], obj["positions"][v][0], obj["positions"][v][1]))
        yield start, len(verts) - start, verts[start:]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("iso", type=Path)
    ap.add_argument("--output", type=Path, required=True)
    a = ap.parse_args()
    with Iso9660(a.iso) as iso:
        entry = AfsArchive(iso, "GDATA.AFS").entries[SLOT]
        chunks = split_pac(iso.read_file("GDATA.AFS", entry["offset"], entry["size"]))
    lines = ["/* Generated by tools/prepare_hud.py from id100.pac. */", "#ifndef DMC3_HUD_RUNTIME_H", "#define DMC3_HUD_RUNTIME_H",
             "typedef struct { float u, v, x, y; } HudVertex;",
             "typedef struct { unsigned int first, count; } HudPart;",
             "typedef struct { const HudVertex *verts; const HudPart *parts; unsigned int part_count, vert_count; int texture; } HudMesh;",
             "typedef struct { int width, height; const unsigned char *rgba; } HudTexture;"]
    textures, meshes, used = [], [], {}
    current = None
    for index in sorted(chunks):
        data = chunks[index]
        if data[:4] == b"PAC\0":
            continue
        if data[:4] != b"MOD ":
            current = index
            continue
        if index not in CHUNKS:
            continue
        if current not in used:
            w, h, rgba = first_texture(chunks[current])
            used[current] = len(textures)
            n = len(textures)
            lines.append(f"static const unsigned char __attribute__((aligned(16))) hud_tex_{n}[] = {{" + ",".join(str(b) for b in rgba) + "};")
            textures.append(f"{{{w},{h},hud_tex_{n}}}")
        name = CHUNKS[index]
        all_verts, parts = [], []
        for start, count, verts in triangles(data):
            parts.append(f"{{{start},{count}}}")
            all_verts += verts
        lines.append(f"static const HudVertex hud_v_{name}[] = {{" + ",".join("{%.5ff,%.5ff,%.3ff,%.3ff}" % v for v in all_verts) + "};")
        lines.append(f"static const HudPart hud_p_{name}[] = {{" + ",".join(parts) + "};")
        meshes.append((name, f"{{hud_v_{name},hud_p_{name},{len(parts)},{len(all_verts)},{used[current]}}}"))
    lines.append(f"#define HUD_TEXTURE_COUNT {len(textures)}")
    lines.append("static const HudTexture hud_textures[] = {" + ",".join(textures) + "};")
    lines.append("enum { " + ", ".join(f"HUD_{n}" for n, _ in meshes) + ", HUD_MESH_COUNT };")
    lines.append("static const HudMesh hud_meshes[] = {" + ",".join(m for _, m in meshes) + "};")
    lines += ["#endif", ""]
    (a.output / "hud_runtime.h").write_text("\n".join(lines), encoding="ascii")
    print(f"Generated hud_runtime.h: {len(meshes)} meshes, {len(textures)} textures")


if __name__ == "__main__":
    main()
