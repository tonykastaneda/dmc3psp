#!/usr/bin/env python3
"""Effect sheets from static_effect.pac (GDATA slot 167) -> fx_runtime.h.

The game's own 128x128 sheets, kept as 8-bit paletted textures: small, and they fit
the PSP's additive sprites as they are.
"""
import argparse
import struct
from pathlib import Path

from PIL import Image

from dmc3_image import AfsArchive, Iso9660
from tim2 import decode_picture

# Index in the pack's order of TIM2 files -> name in fx.h. See analysis/ref/fx_textures.png.
SHEETS = {
    "SMOKE": 0,    # 2x2 smoke puffs
    "FLARE": 1,    # 2x2 burst, star glow, sparkle, vertical streak
    "BITS": 4,     # 4x4 blobs, debris, ring, flares
    "SPARK_A": 6,  # one spark burst
    "SPARK_B": 7,  # another
    "FIRE": 9,     # 2x2 explosion
    "RAYS": 11,    # top ray fan, bottom lightning
    "GLOW": 13,    # discs, ring, flash streak, lightning
    "LINES": 14,   # speed lines
}


def to_indexed(rgba, width, height):
    image = Image.frombytes("RGBA", (width, height), bytes(rgba))
    # Palette by quantizing colour and alpha together.
    quant = image.quantize(colors=256, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.NONE)
    palette = quant.getpalette("RGBA")
    return bytes(quant.getdata()), palette + [0] * (1024 - len(palette))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("iso", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    iso = Iso9660(args.iso)
    entry = AfsArchive(iso, "GDATA.AFS").entries[167]
    data = iso.read_file("GDATA.AFS", entry["offset"], entry["size"])
    positions = []
    at = data.find(b"TIM2")
    while at >= 0:
        positions.append(at)
        at = data.find(b"TIM2", at + 4)
    lines = ["/* Generated by tools/prepare_fx.py from static_effect.pac. */",
             "#define FX_TEX_SIZE 128", f"#define FX_SHEET_COUNT {len(SHEETS)}", "typedef enum {"]
    lines += [f"    FX_SHEET_{name}," for name in SHEETS]
    lines += ["} FxSheet;"]
    for name, index in SHEETS.items():
        image = data[positions[index]:]
        _, rgba, picture = decode_picture(image, 0x80 if image[5] == 1 else 0x10)
        pixels, palette = to_indexed(rgba, picture["width"], picture["height"])
        lines.append(f"static const unsigned char fx_pixels_{name}[] __attribute__((aligned(16))) = {{{','.join(map(str, pixels))}}};")
        words = [palette[i] | palette[i + 1] << 8 | palette[i + 2] << 16 | palette[i + 3] << 24 for i in range(0, 1024, 4)]
        lines.append(f"static const unsigned int fx_palette_{name}[256] __attribute__((aligned(16))) = {{{','.join(map(hex, words))}}};")
    lines.append("static const unsigned char *const fx_pixels[FX_SHEET_COUNT] = {" + ",".join(f"fx_pixels_{n}" for n in SHEETS) + "};")
    lines.append("static const unsigned int *const fx_palettes[FX_SHEET_COUNT] = {" + ",".join(f"fx_palette_{n}" for n in SHEETS) + "};")
    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / "fx_runtime.h").write_text("\n".join(lines) + "\n", encoding="ascii")
    print(f"Generated fx_runtime.h: {len(SHEETS)} sheets")


if __name__ == "__main__":
    main()
