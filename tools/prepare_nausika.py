#!/usr/bin/env python3
"""Export Nausika's three stage actors from the user's disc (st303 pack).
Generated arrays remain local; this script contains no game data.
"""
import argparse
import hashlib
import json
from pathlib import Path
from dmc3_image import Iso9660, AfsArchive
from mod_skeleton import parse_skeleton
from mot_ps2 import parse_mot
from gen_enemy_ai import Elf
from prepare_skinned_model import (pac_list, build_mesh, array_lines, vec,
                                   indexed_texture, decode_textures, c_float)


def generate(iso_path, output):
    output.mkdir(parents=True, exist_ok=True)
    with Iso9660(iso_path) as iso:
        afs = AfsArchive(iso, 'GDATA.AFS')
        entry = afs.entries[692]
        raw = iso.read_file('GDATA.AFS', entry['offset'], entry['size'])
        elf = Elf(iso.read_file('SLUS_213.61', 0, iso.files['SLUS_213.61']['size']))
    stage = pac_list(raw)
    pack = pac_list(stage[5])
    lines = ['/* Generated by prepare_nausika.py; include model_runtime.h first. */', '#pragma once',
             'typedef struct { const Dmc3Vec3 *positions, *normals, *local, *rest; const Dmc3Uv *uvs;',
             'const unsigned char (*bones)[3], (*weights)[3]; const signed char *parents;',
             'const unsigned short *indices; const Dmc3ModelObject *objects;',
             'int vertices, indices_count, objects_count, bone_count; } NausikaMesh;']
    table, manifest, motion_lines, blobs = [], [], ['#pragma once'], []
    for part, chunk in enumerate((100,)):
        model = b'MOD ' + pack[chunk][4:]
        skel = parse_skeleton(model)
        mesh = build_mesh(model, skel['count'])
        n = f'ns{part}'
        arrays = [('Dmc3Vec3', 'positions', mesh['positions'], vec),
                  ('Dmc3Vec3', 'normals', mesh['normals'], vec),
                  ('Dmc3Vec3', 'local', skel['local'], vec),
                  ('Dmc3Vec3', 'rest', skel['world'], vec),
                  ('Dmc3Uv', 'uvs', mesh['uvs'], vec),
                  ('signed char', 'parents', skel['parents'], str),
                  ('unsigned short', 'indices', mesh['indices'], str)]
        for ctype, field, data, formatter in arrays:
            lines += [f'static const {ctype} {n}_{field}[] = {{', array_lines(data, formatter), '};']
        for field in ('bones', 'weights'):
            lines += [f'static const unsigned char {n}_{field}[][3] = {{',
                      array_lines(mesh[field], lambda v: '{' + ','.join(map(str, v)) + '}'), '};']
        lines += [f'static const Dmc3ModelObject {n}_objects[] = {{',
                  array_lines(mesh['objects'], lambda o: '{%d,%d,%d}' %
                              (o['index_start'], o['index_count'], o['texture'])), '};']
        fields = ('positions', 'normals', 'local', 'rest', 'uvs', 'bones', 'weights', 'parents', 'indices', 'objects')
        table.append('{' + ','.join(f'{n}_{f}' for f in fields) +
                     f",{len(mesh['positions'])},{len(mesh['indices'])},{len(mesh['objects'])},{skel['count']}" + '}')
        for slot, mot in enumerate(pac_list(pack[chunk+1])):
            if not mot: continue
            try:
                parsed = parse_mot(mot)
            except ValueError as error:
                print(f'Nausika motion {slot} skipped: {error}')
                continue
            data = mot[:parsed['bytes_used']]
            ident = f'ns_mot_{part}_{slot}'
            motion_lines += [f'static const unsigned char {ident}[] __attribute__((aligned(4))) = {{',
                             array_lines(data, str, 24), '};']
            blobs.append(f'{{"ns{part}-{slot:02d}",{ident},{len(data)}}}')
        manifest.append({'part': part, 'chunk': chunk, 'bones': skel['count'],
                         'vertices': len(mesh['positions']), 'sha256': hashlib.sha256(model).hexdigest()})
    import re
    game=stage[4].decode('latin1')
    block=game[game.index('# SET 777 NAUSIKA'):]
    block=block.split('root',1)[1].split('# SET',1)[0]
    points=[tuple(map(float,m)) for m in re.findall(r'(-?\d+(?:\.\d+)?)\s*,\s*(-?\d+(?:\.\d+)?)\s*,\s*(-?\d+(?:\.\d+)?)',block)]
    lines += [f'#define NAUSIKA_PATH_COUNT {len(points)}', 'static const Dmc3Vec3 nausika_path[] = {'+','.join(vec(p) for p in points)+'};']
    lines += ['static const NausikaMesh nausika_parts[] = {' + ','.join(table) + '};']
    textures = decode_textures(stage[1])
    for i, tx in enumerate(textures):
        pixels, palette = indexed_texture(tx)
        lines += [f'static const unsigned char ns_texture_{i}[] = {{', array_lines(pixels, str, 24), '};',
                  f'static const unsigned int ns_palette_{i}[256] __attribute__((aligned(16))) = {{',
                  array_lines(palette, lambda x: f'0x{x:08x}u', 8), '};']
    lines += [f'#define NAUSIKA_TEXTURE_COUNT {len(textures)}',
              'static const Dmc3Texture nausika_textures[] = {' + ','.join(
                  f"{{{tx['width']},{tx['height']},ns_texture_{i}}}" for i,tx in enumerate(textures)) + '};',
              'static const unsigned int *const nausika_palettes[] = {' + ','.join(
                  f'ns_palette_{i}' for i in range(len(textures))) + '};']
    (output/'boss_nausika_runtime.h').write_text('\n'.join(lines)+'\n', encoding='ascii')
    motion_lines += [f'#define NAUSIKA_MOTION_COUNT {len(blobs)}',
                     'static const Dmc3MotionBlob nausika_motion_blobs[] = {' + ','.join(blobs) + '};']
    (output/'boss_nausika_motions.h').write_text('\n'.join(motion_lines)+'\n', encoding='ascii')
    (output/'boss_nausika_manifest.json').write_text(json.dumps({'parts':manifest,'motions':len(blobs)},indent=2)+'\n')
    print(f'Nausika: 1 actor, {len(blobs)} motions, {len(textures)} textures -> {output}')

if __name__ == '__main__':
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('iso', type=Path)
    ap.add_argument('--output', required=True, type=Path)
    args=ap.parse_args()
    generate(args.iso,args.output)
