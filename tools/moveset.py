"""Join the decoded tables into docs/MOVESET.md (Dante, SE).

command_table.csv (input, posture, weapon, style, conditions)
  -> action id -> action_dispatch.json (handler function)
  -> motion_calls.csv (scripts the handler requests)
  -> motion_scripts.json (motions played, attack-active frames, gate timings).

Timeline frames are motion frames: a script segment runs once the motion
passes the preceding wait frame (FUN_00255160).
"""
import argparse
import csv
import json
from collections import defaultdict
from pathlib import Path

WEAPONS = ["Rebellion", "Cerberus", "Agni & Rudra", "Nevan", "Beowulf",
           "Ebony & Ivory", "Shotgun", "Artemis", "Spiral", "Kalina Ann"]
STYLES = ["Swordmaster", "Gunslinger", "Trickster", "Royalguard", "Quicksilver", "Doppelganger"]
TYPES = {0: "melee", 1: "gun", 2: "directional", 3: "style"}


def runtime_name(f, i):
    """Motion name as the test room build exports it (prepare_skinned_model.py)."""
    if f <= 2:
        return f"{f + 2}-{i:02d}"
    if f == 3:
        return f"rb-{i:02d}"
    return f"s{20 + f}-{i:02d}"


def ranges(frames_on):
    out, start = [], None
    for f, on in frames_on:
        if on and start is None:
            start = f
        elif not on and start is not None:
            out.append(f"{start}-{f}")
            start = None
    if start is not None:
        out.append(f"{start}-end")
    return out


def timeline(script):
    frame, motions, active, gates = 0, [], [], defaultdict(list)
    for op in script["ops"]:
        if op["op"] == 0:
            frame = op["wait"] if op["wait"] != 0x7FFF else "end"
            if frame == "end":
                break
        elif op["op"] == 1 and op.get("def"):
            for l in op["def"]["layers"]:
                if l["layer"] == 0:
                    motions.append(runtime_name(l["file"], l["index"]))
        elif op["op"] == 3:
            active.append((frame, bool(int(op["raw"][4:6], 16) & 0x80)))
        elif op["op"] == 4:
            for k in range(5):
                b = int(op["raw"][2 + 2 * k: 4 + 2 * k], 16)
                if b >> 4 == 1:
                    gates[b & 0xF].append(frame)
    return motions, ranges(active), gates


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--moveset", type=Path, default=Path("analysis/moveset"))
    ap.add_argument("--out", type=Path, default=Path("docs/MOVESET.md"))
    a = ap.parse_args()
    m = a.moveset
    cmds = list(csv.DictReader((m / "command_table.csv").open()))
    dispatch = json.loads((m / "action_dispatch.json").read_text())
    scripts = json.loads((m / "motion_scripts.json").read_text())
    calls = defaultdict(list)
    for r in csv.DictReader((m / "motion_calls.csv").open()):
        key = f"{r['bank']}:{r['index']}"
        if key not in calls[int(r["function"], 16)]:
            calls[int(r["function"], 16)].append(key)

    lines = ["# Dante moveset (DMC3 SE, from game data)", "",
             "Generated by `tools/moveset.py` from the command table (0x5a8e90), the",
             "action dispatcher (FUN_002625d0) and the motion scripts (archive chunk 5).",
             "See docs/MOVESET_RE.md for how each column is derived. Names of moves",
             "are not in the data; *action* is the game's own id.", "",
             "Columns: **input** (R1 = lock-on; fwd/back relative to Dante or the",
             "target), **needs** (gate *n* open, or `after N` = follow-up of action",
             "N), **scripts** (bank:index, in source order), **motions** (runtime names;",
             "`rb-` = GDATA 23, `sNN-` = GDATA NN), **active** (script: attack-active",
             "frame ranges), **opens** (gate@frames it opens, first listed script).", ""]
    groups = defaultdict(list)
    for c in cmds:
        w = int(c["weapon"])
        if int(c["type"]) == 3:
            st = int(c["style"])
            key = f"{STYLES[st]}" + (f" - {WEAPONS[w & 0x7F]}" if 0 <= w < 0x80 else "")
        else:
            key = WEAPONS[w & 0x7F] if w >= 0 else "Any weapon"
        groups[key].append(c)
    for key, rows in groups.items():
        lines += [f"## {key}", "",
                  "| action | type | posture | input | needs | scripts | motions | active | opens |",
                  "|---|---|---|---|---|---|---|---|---|"]
        for c in rows:
            d = dispatch.get(c["action"])
            sc = calls.get(int(d["handler"], 16), []) if d else []
            mots, active, opens = [], [], {}
            for i, k in enumerate(sc):
                if k in scripts:
                    mo, ac, ga = timeline(scripts[k])
                    mots += [x for x in mo if x not in mots]
                    if ac:
                        active.append(f"{k}:{','.join(ac)}")
                    if i == 0:
                        opens = ga
            cond = c["conditions"].replace("gate15?", "").strip()
            lines.append("| {} | {} | {} | {} | {} | {} | {} | {} | {} |".format(
                c["action"], TYPES.get(int(c["type"]), c["type"]), c["posture"],
                c["input_text"], cond, " ".join(sc), " ".join(mots),
                " ".join(active), " ".join(f"g{g}@{','.join(map(str, f))}" for g, f in sorted(opens.items()))))
        lines.append("")
    a.out.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(cmds)} commands in {len(groups)} groups -> {a.out}")


if __name__ == "__main__":
    main()
