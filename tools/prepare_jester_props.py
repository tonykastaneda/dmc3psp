#!/usr/bin/env python3
"""The Jester's bomb and animated hand -> jester_props_runtime.h (docs/ENEMY_SPECS.md, the Jester).

em037.pac (GDATA 140, a PAC) holds them beside his body; their projectiles find them through the pack's offset table:
  - the bomb his ball attack throws (FUN_0054de00, entry 0x19 + 2 x variant): [25], a spiked ball about 170 cm
    across, textures [24];
  - the trap (FUN_0054c660 / FUN_0054caa0: +0x70, +0x74, +0x78): [27], a giant hand that rises from the floor,
    textures [26], its 120-frame finger motion [28].
The bomb stays rigid; the hand retains its skeleton, vertex weights and native motion. Each mesh is a list of batches by texture, vertices as
{u, v, colour, x, y, z} with a light from above baked into the colour; textures as 8-bit with a palette.

    python tools/prepare_jester_props.py <iso> --output build/testroom/generated

Everything it reads and writes stays local (generated/ is ignored).
"""
import argparse
from pathlib import Path

from mot_ps2 import parse_mot

from dmc3_image import AfsArchive, Iso9660
from prepare_skinned_model import (array_lines, build_mesh, c_float, decode_textures, indexed_texture, pac_list,
                                   parse_skeleton)

SLOT = 140
PROPS = (("bomb", 25, 24), ("hand", 27, 26))


def mesh_batches(mod, textures_raw):
    if mod[:4] == b"EFM ":
        mod = b"MOD " + mod[4:]
    mesh = build_mesh(mod, parse_skeleton(mod)["count"])
    textures = decode_textures(textures_raw)
    batches = {}
    for obj in mesh["objects"]:
        tex = obj["texture"] if obj["texture"] < len(textures) else 0
        out = batches.setdefault(tex, [])
        for i in mesh["indices"][obj["index_start"]:obj["index_start"] + obj["index_count"]]:
            x, y, z = mesh["positions"][i]
            u, v = mesh["uvs"][i]
            ny = mesh["normals"][i][1]
            shade = int(150 + 105 * max(0.0, ny))
            out.append((u, v, 0xff000000 | shade << 16 | shade << 8 | shade, x, y, z,
                        *mesh["bones"][i], *mesh["weights"][i]))
    return batches, textures


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("iso", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    with Iso9660(args.iso) as iso:
        entry = AfsArchive(iso, "GDATA.AFS").entries[SLOT]
        pack = pac_list(iso.read_file("GDATA.AFS", entry["offset"], entry["size"]))
    lines = ["/* Generated by tools/prepare_jester_props.py: bomb and animated hand. */", "#pragma once",
             "typedef struct { float u, v; unsigned int color; float x, y, z; } JesterPropVertex;",
             "typedef struct { const JesterPropVertex *vertices; int count, width, height; const unsigned char *pixels;"
             " const unsigned int *palette; const unsigned char (*skin)[6]; } JesterPropBatch;",
             "typedef struct { const JesterPropBatch *batches; int count; } JesterProp;"]
    table = []
    for name, model, tex_entry in PROPS:
        batches, textures = mesh_batches(pack[model], pack[tex_entry])
        if name == "hand":
            skeleton = parse_skeleton(pack[model])
            for key in ("local", "world"):
                lines += [f"static const float jp_hand_{key}[][3] = {{",
                          array_lines(skeleton[key], lambda v: "{" + ",".join(c_float(x) for x in v) + "}", 3), "};"]
            lines += ["static const signed char jp_hand_parent[] = {" + ",".join(map(str, skeleton["parents"])) + "};"]
            motion = pac_list(pack[28])[0]
            motion = motion[:parse_mot(motion)["bytes_used"]]
            lines += ["static const unsigned char jp_hand_motion[] __attribute__((aligned(4))) = {",
                      array_lines(motion, str, 32), "};"]
        rows = []
        for tex, verts in sorted(batches.items()):
            t = textures[tex]
            pixels, palette = indexed_texture(t)
            p = f"jp_{name}_{tex}"
            lines += [f"static const JesterPropVertex {p}_v[] __attribute__((aligned(16))) = {{",
                      array_lines(verts, lambda v: "{%s,%s,0x%08xu,%s,%s,%s}" % (
                          c_float(v[0]), c_float(v[1]), v[2], c_float(v[3]), c_float(v[4]), c_float(v[5])), 2), "};",
                      f"static const unsigned char {p}_pixels[] __attribute__((aligned(16))) = {{",
                      array_lines(pixels, str, 32), "};",
                      f"static const unsigned int {p}_palette[256] __attribute__((aligned(16))) = {{",
                      array_lines(palette, lambda c: f"0x{c:08x}u", 8), "};"]
            skin = "0"
            if name == "hand":
                lines += [f"static const unsigned char {p}_skin[][6] = {{",
                          array_lines(verts, lambda v: "{" + ",".join(map(str, v[6:])) + "}", 6), "};"]
                skin = f"{p}_skin"
            rows.append(f"{{{p}_v,{len(verts)},{t['width']},{t['height']},{p}_pixels,{p}_palette,{skin}}}")
        lines.append(f"static const JesterPropBatch jp_{name}_batches[] = {{" + ",".join(rows) + "};")
        table.append(f"{{jp_{name}_batches,{len(rows)}}}")
        print(f"{name}: [{model}], {sum(len(v) for v in batches.values()) // 3} triangles, {len(rows)} textures")
    lines.append("enum { JESTER_PROP_BOMB, JESTER_PROP_HAND };")
    lines.append("static const JesterProp jester_props[] = {" + ",".join(table) + "};")
    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / "jester_props_runtime.h").write_text("\n".join(lines) + "\n", encoding="ascii")


if __name__ == "__main__":
    main()
